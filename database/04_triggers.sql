-- =============================================================================
-- Smart HAS — Oracle Database: Auditoria e automação (Triggers)
-- =============================================================================
-- AUDIT_LOG                  -> tabela genérica de auditoria
-- TRG_SENSOR_ALERT_AUDIT     -> registra automaticamente todo alerta criado
-- TRG_DELIVERY_STATUS_AUDIT  -> registra automaticamente toda mudança de
--                                status de um pedido de entrega
-- =============================================================================

PROMPT Creating table AUDIT_LOG...
BEGIN EXECUTE IMMEDIATE 'DROP TABLE audit_log PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
CREATE TABLE audit_log (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    table_name  VARCHAR2(60)  NOT NULL,
    operation   VARCHAR2(30)  NOT NULL,
    record_id   NUMBER        NOT NULL,
    old_value   VARCHAR2(200),
    new_value   VARCHAR2(200),
    changed_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_audit_log_table ON audit_log (table_name, changed_at);

-- -----------------------------------------------------------------------------
-- TRG_SENSOR_ALERT_AUDIT
-- Dispara a cada INSERT em SENSOR_ALERT (ou seja, toda vez que
-- PRC_REGISTER_CRITICAL_ALERT registra um alerta) e grava o evento em
-- AUDIT_LOG automaticamente — nenhuma chamada explícita é necessária em
-- nenhuma camada da aplicação. Cobre o exemplo "registrar logs de alertas"
-- citado na atividade.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_sensor_alert_audit
AFTER INSERT ON sensor_alert
FOR EACH ROW
BEGIN
    INSERT INTO audit_log (table_name, operation, record_id, old_value, new_value)
    VALUES (
        'SENSOR_ALERT',
        'ALERT_CREATED',
        :NEW.id,
        NULL,
        :NEW.alert_level || ': ' || :NEW.message
    );
EXCEPTION
    WHEN OTHERS THEN
        -- Auditoria nunca pode quebrar o fluxo principal (o alerta já foi
        -- gravado); apenas registra a falha de log, sem propagar o erro.
        NULL;
END trg_sensor_alert_audit;
/

-- -----------------------------------------------------------------------------
-- TRG_DELIVERY_STATUS_AUDIT
-- Dispara a cada UPDATE de status em MEDICATION_DELIVERY_REQUEST e grava o
-- "antes/depois" em AUDIT_LOG — cobre o exemplo "atualizar status
-- automaticamente" citado na atividade: o backend (ou o admin via
-- dashboard) só precisa atualizar a coluna status; o rastro de auditoria é
-- automático, sem código extra em nenhuma camada.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_delivery_status_audit
AFTER UPDATE OF status ON medication_delivery_request
FOR EACH ROW
WHEN (NVL(OLD.status, '*') != NVL(NEW.status, '*'))
BEGIN
    INSERT INTO audit_log (table_name, operation, record_id, old_value, new_value)
    VALUES (
        'MEDICATION_DELIVERY_REQUEST',
        'STATUS_CHANGE',
        :NEW.id,
        :OLD.status,
        :NEW.status
    );
EXCEPTION
    WHEN OTHERS THEN
        NULL;
END trg_delivery_status_audit;
/

